import assert from "node:assert/strict";
import { grantProvidesAccess, subscriptionProvidesAccess } from "../lib/billing/status";
const hour = 60 * 60 * 1000;
const now = new Date("2026-01-15T12:00:00.000Z");
const before = new Date(now.getTime() - hour);
const after = new Date(now.getTime() + hour);
assert.equal(subscriptionProvidesAccess({ status: "ACTIVE" }, now), true);
assert.equal(subscriptionProvidesAccess({ status: "ACTIVE", currentPeriodEnd: before }, now), false);
assert.equal(subscriptionProvidesAccess({ status: "TRIALING", currentPeriodEnd: after }, now), true);
assert.equal(subscriptionProvidesAccess({ status: "PAST_DUE" }, now), false);
assert.equal(subscriptionProvidesAccess({ status: "PAST_DUE", currentPeriodEnd: after }, now), true);
assert.equal(subscriptionProvidesAccess({ status: "CANCELED", currentPeriodEnd: after }, now), true);
assert.equal(subscriptionProvidesAccess({ status: "CANCELED", currentPeriodEnd: before }, now), false);
assert.equal(subscriptionProvidesAccess({ status: "CANCELLED", currentPeriodEnd: after }, now), true);
assert.equal(subscriptionProvidesAccess({ status: "SUSPENDED", currentPeriodEnd: after }, now), false);
assert.equal(subscriptionProvidesAccess({ status: "EXPIRED", currentPeriodEnd: after }, now), false);
assert.equal(grantProvidesAccess({ startsAt: before, expiresAt: null }, now), true);
assert.equal(grantProvidesAccess({ startsAt: after, expiresAt: null }, now), false);
assert.equal(grantProvidesAccess({ startsAt: before, expiresAt: before }, now), false);
assert.equal(grantProvidesAccess({ startsAt: before, revokedAt: now }, now), false);
console.log("billing status tests passed");
