async function main() {
  console.log("🚀 正在注入扩充的国内外顶尖程序员招聘岗位池...");

  let added = 0;
  for (const item of ALL_PROGRAMMER_JOBS) {
    const exists = await prisma.job.findFirst({
      where: {
        AND: [{ company: item.company }, { title: item.title }],
      },
    });

    if (!exists) {
      await prisma.job.create({
        data: item,
      });
      added++;
    }
  }

  const total = await prisma.job.count();
  console.log(`🎉 成功同步！全库程序员专属在招岗位现已达到 【${total} 个】！`);
}

main().catch(console.error).finally(() => prisma.$disconnect());